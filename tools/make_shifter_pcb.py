"""Lay out the Synth Mage shifter / distribution PCB with KiCad's pcbnew module.

Run with KiCad's own Python so the module and footprint libraries are found:

  "C:\\Program Files\\KiCad\\10.0\\bin\\python.exe" tools\\make_shifter_pcb.py

Writes hardware/shifter-board/shifter-board.kicad_pcb. Nets and pin numbers follow
the schematic generated by tools/make_shifter_schematic.py; check with

  kicad-cli pcb drc --schematic-parity --severity-all --format report -o drc.txt hardware\\shifter-board\\shifter-board.kicad_pcb
  kicad-cli pcb render -o docs\\diagrams\\shifter-board-3d.png --quality high --perspective --rotate "-40,0,-30" hardware\\shifter-board\\shifter-board.kicad_pcb

Board: 52 x 56 mm, two layers. Chip vertical in the middle (notch at the top),
pin header J6 for the ESP32 leads down the left edge, four 3-way screw terminals
J1..J4 down the right edge (top to bottom: GND, data, +5V), C1 and the 2-way
USB screw terminal J5 along the bottom. GND is a copper pour on the back;
+5V is a 0.8 mm track that runs round the left, top and right edges.
"""
import os
import pcbnew

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "hardware", "shifter-board", "shifter-board.kicad_pcb")
FP = r"C:\Program Files\KiCad\10.0\share\kicad\footprints"

OX, OY = 100.0, 100.0        # board origin on the KiCad sheet
BW, BH = 52.0, 56.0          # board size, mm


def P(x, y):
    """Board-local mm -> KiCad vector."""
    return pcbnew.VECTOR2I_MM(OX + x, OY + y)


def local(v):
    return (v.x / 1e6 - OX, v.y / 1e6 - OY)


board = pcbnew.BOARD()
ds = board.GetDesignSettings()
ds.SetCopperLayerCount(2)

# ------------------------------------------------------------------ nets
NET_NAMES = ["+5V", "GND", "/GPIO4", "/GPIO5", "/GPIO6", "/GPIO7",
             "Net-(J1-Pin_2)", "Net-(J2-Pin_2)", "Net-(J3-Pin_2)", "Net-(J4-Pin_2)",
             "Net-(R1-Pad1)", "Net-(R2-Pad1)", "Net-(R3-Pad1)", "Net-(R4-Pad1)"]
nets = {}
for n in NET_NAMES:
    ni = pcbnew.NETINFO_ITEM(board, n)
    board.Add(ni)
    nets[n] = ni

# pad -> net, straight from the schematic netlist
PAD_NETS = {
    ("U1", "14"): "+5V", ("U1", "7"): "GND", ("U1", "1"): "GND", ("U1", "4"): "GND",
    ("U1", "10"): "GND", ("U1", "13"): "GND",
    ("U1", "2"): "/GPIO4", ("U1", "5"): "/GPIO5", ("U1", "12"): "/GPIO6", ("U1", "9"): "/GPIO7",
    ("U1", "3"): "Net-(R1-Pad1)", ("U1", "6"): "Net-(R2-Pad1)", ("U1", "11"): "Net-(R3-Pad1)", ("U1", "8"): "Net-(R4-Pad1)",
    ("R1", "1"): "Net-(R1-Pad1)", ("R1", "2"): "Net-(J1-Pin_2)",
    ("R2", "1"): "Net-(R2-Pad1)", ("R2", "2"): "Net-(J2-Pin_2)",
    ("R3", "1"): "Net-(R3-Pad1)", ("R3", "2"): "Net-(J3-Pin_2)",
    ("R4", "1"): "Net-(R4-Pad1)", ("R4", "2"): "Net-(J4-Pin_2)",
    ("J1", "1"): "+5V", ("J1", "2"): "Net-(J1-Pin_2)", ("J1", "3"): "GND",
    ("J2", "1"): "+5V", ("J2", "2"): "Net-(J2-Pin_2)", ("J2", "3"): "GND",
    ("J3", "1"): "+5V", ("J3", "2"): "Net-(J3-Pin_2)", ("J3", "3"): "GND",
    ("J4", "1"): "+5V", ("J4", "2"): "Net-(J4-Pin_2)", ("J4", "3"): "GND",
    ("J5", "1"): "GND", ("J5", "2"): "+5V",
    ("J6", "1"): "+5V", ("J6", "2"): "/GPIO6", ("J6", "3"): "/GPIO4", ("J6", "4"): "/GPIO5", ("J6", "5"): "/GPIO7", ("J6", "6"): "GND",
    ("C1", "1"): "+5V", ("C1", "2"): "GND",
}

# ------------------------------------------------------------------ footprints
fps = {}


def footprint(ref, value, lib, name, x, y, rot=0, show_ref=True):
    fp = pcbnew.FootprintLoad(os.path.join(FP, lib + ".pretty"), name)
    fp.SetFPIDAsString("%s:%s" % (lib, name))
    fp.SetReference(ref)
    fp.SetValue(value)
    fp.SetPosition(P(x, y))
    fp.SetOrientationDegrees(rot)
    fp.Value().SetVisible(False)
    fp.Reference().SetVisible(show_ref)
    if ref.startswith("H"):
        fp.SetExcludedFromBOM(True)
    board.Add(fp)
    for pad in fp.Pads():
        key = (ref, pad.GetNumber())
        if key in PAD_NETS:
            pad.SetNet(nets[PAD_NETS[key]])
    fps[ref] = fp
    return fp


def pad(ref, num):
    return local(fps[ref].FindPadByNumber(str(num)).GetPosition())


TERM3 = ("TerminalBlock_Phoenix", "TerminalBlock_Phoenix_MPT-0,5-3-2.54_1x03_P2.54mm_Horizontal")
TERM2 = ("TerminalBlock_Phoenix", "TerminalBlock_Phoenix_MPT-0,5-2-2.54_1x02_P2.54mm_Horizontal")

# chip: pad 1 at (19, 11.5); pins 1-7 go down the left column, 14-8 down the right column
footprint("U1", "SN74AHCT125N", "Package_DIP", "DIP-14_W7.62mm_Socket", 19.0, 11.5)
# resistors, horizontal, pad 1 at x = 29.5. Each row lines up with its output terminal's data pin.
RX = 30.0
ROWS = {"R1": 12.54, "R2": 22.70, "R3": 32.86, "R4": 43.02}
for r, y in ROWS.items():
    footprint(r, "220R", "Resistor_THT", "R_Axial_DIN0207_L6.3mm_D2.5mm_P10.16mm_Horizontal", RX, y)
# output screw terminals down the right edge. Rotation 90 puts pin 1 (+5V) at the bottom,
# pin 2 (data) in the middle, pin 3 (GND) on top, with the mounting pegs on the outside.
TX = 45.5
OUT_VALUES = {"J1": "OUT1 left front", "J2": "OUT2 right front", "J3": "OUT3 left drape", "J4": "OUT4 right drape"}
for j, r in (("J1", "R1"), ("J2", "R2"), ("J3", "R3"), ("J4", "R4")):
    footprint(j, OUT_VALUES[j], TERM3[0], TERM3[1], TX, ROWS[r] + 2.54, rot=90, show_ref=False)
    assert abs(pad(j, 2)[1] - ROWS[r]) < 0.01 and pad(j, 1)[1] > pad(j, 3)[1]
# ESP32 leads down the left edge, pin 1 at the top
footprint("J6", "ESP32-S3 leads", "Connector_PinHeader_2.54mm", "PinHeader_1x06_P2.54mm_Vertical", 5.0, 13.5)
# bulk capacitor, + pad on the left
footprint("C1", "1000uF", "Capacitor_THT", "CP_Radial_D10.0mm_P5.00mm", 10.5, 40.5)
# USB in: 2-way screw terminal along the bottom edge, pin 1 (GND) left, pin 2 (+5V) right
footprint("J5", "USB 5V in", TERM2[0], TERM2[1], 23.0, 47.5)
# mounting holes
for i, (x, y) in enumerate(((3.5, 3.5), (BW - 3.5, 3.5), (3.5, BH - 3.5), (BW - 3.5, BH - 3.5)), 1):
    footprint("H%d" % i, "M3", "MountingHole", "MountingHole_3.2mm_M3", x, y, show_ref=False)

# ------------------------------------------------------------------ board outline
edge = pcbnew.PCB_SHAPE(board)
edge.SetShape(pcbnew.SHAPE_T_RECT)
edge.SetStart(P(0, 0))
edge.SetEnd(P(BW, BH))
edge.SetLayer(pcbnew.Edge_Cuts)
edge.SetWidth(pcbnew.FromMM(0.1))
board.Add(edge)

# ------------------------------------------------------------------ tracks


def track(net, layer, width, *pts):
    for a, b in zip(pts, pts[1:]):
        t = pcbnew.PCB_TRACK(board)
        t.SetStart(P(*a))
        t.SetEnd(P(*b))
        t.SetWidth(pcbnew.FromMM(width))
        t.SetLayer(layer)
        t.SetNet(nets[net])
        board.Add(t)


F, B = pcbnew.F_Cu, pcbnew.B_Cu
PWR, SIG, THIN = 0.8, 0.4, 0.3
BUS_X = BW - 2.0             # +5V bus down the right edge, outside the terminal pegs

# +5V: USB in -> C1+ -> up the left edge -> along the top -> down the right edge
j5_5v = pad("J5", 2)
c1p = pad("C1", 1)
track("+5V", F, PWR, j5_5v, (j5_5v[0], 44.0), (c1p[0], 44.0), c1p)
track("+5V", F, PWR, c1p, (c1p[0], 37.0), (2.5, 37.0), (2.5, 8.0), (BUS_X, 8.0), (BUS_X, pad("J4", 1)[1] + 1.5))
track("+5V", F, PWR, (2.5, pad("J6", 1)[1]), pad("J6", 1))
track("+5V", F, PWR, (pad("U1", 14)[0], 8.0), pad("U1", 14))
# each terminal's +5V pin is fed from below, between it and the next block, clear of the pegs
for j in ("J1", "J2", "J3", "J4"):
    x, y = pad(j, 1)
    track("+5V", F, 0.6, (BUS_X, y + 1.5), (x + 0.5, y + 1.5), (x, y + 1.0), (x, y))

# inputs on the top layer: GPIO4 -> pin 2, GPIO5 -> pin 5 (both on the chip's left column)
track("/GPIO4", F, SIG, pad("J6", 3), (9.0, pad("J6", 3)[1]), (13.54, pad("U1", 2)[1]), pad("U1", 2))
track("/GPIO5", F, SIG, pad("J6", 4), (14.46, pad("J6", 4)[1]), (15.0, pad("U1", 5)[1]), pad("U1", 5))
# inputs on the bottom layer, passing between the chip's pads: GPIO6 -> pin 12, GPIO7 -> pin 9 (right column)
track("/GPIO6", B, THIN, pad("J6", 2), (9.0, pad("J6", 2)[1]), (9.73, 15.31), (25.35, 15.31), pad("U1", 12))
track("/GPIO7", B, THIN, pad("J6", 5), (10.0, pad("J6", 5)[1]), (11.81, 25.47), (25.35, 25.47), pad("U1", 9))
# outputs from the left column cross under the chip on the bottom layer to R1 and R2
track("Net-(R1-Pad1)", B, THIN, pad("U1", 3), (20.27, 17.85), (28.0, 17.85), (RX, 15.85), pad("R1", 1))
track("Net-(R2-Pad1)", B, THIN, pad("U1", 6), (20.27, 22.93), (28.0, 22.93), (28.23, ROWS["R2"]), pad("R2", 1))
# outputs from the right column go down to R3 and R4 on the top layer
track("Net-(R3-Pad1)", F, SIG, pad("U1", 11), (28.3, 20.8), (28.3, ROWS["R3"] - 1.0), (RX - 0.7, ROWS["R3"]), pad("R3", 1))
track("Net-(R4-Pad1)", F, SIG, pad("U1", 8), (27.2, 27.32), (27.2, ROWS["R4"] - 2.8), pad("R4", 1))
# resistor to terminal data pin
for r, j in (("R1", "J1"), ("R2", "J2"), ("R3", "J3"), ("R4", "J4")):
    track("Net-(%s-Pin_2)" % j, F, SIG, pad(r, 2), pad(j, 2))

# ------------------------------------------------------------------ GND pour on the back
zone = pcbnew.ZONE(board)
zone.SetLayer(B)
zone.SetNet(nets["GND"])
zone.SetZoneName("GND")
outline = zone.Outline()
outline.NewOutline()
for x, y in ((0, 0), (BW, 0), (BW, BH), (0, BH)):
    outline.Append(P(x, y))
zone.SetPadConnection(pcbnew.ZONE_CONNECTION_THERMAL)
zone.SetMinThickness(pcbnew.FromMM(0.25))
zone.SetLocalClearance(pcbnew.FromMM(0.3))
zone.SetThermalReliefGap(pcbnew.FromMM(0.4))
zone.SetThermalReliefSpokeWidth(pcbnew.FromMM(0.6))
board.Add(zone)

# ------------------------------------------------------------------ silkscreen


def text(s, x, y, size=0.8, rot=0, layer=pcbnew.F_SilkS, bold=False):
    t = pcbnew.PCB_TEXT(board)
    t.SetText(s)
    t.SetPosition(P(x, y))
    t.SetLayer(layer)
    t.SetTextSize(pcbnew.VECTOR2I_MM(size, size))
    t.SetTextThickness(pcbnew.FromMM(size * 0.15))
    t.SetTextAngleDegrees(rot)
    t.SetBold(bold)
    board.Add(t)


text("SYNTH MAGE SHIFTER v1", BW / 2, 4.2, 1.2, bold=True)
for num, lab in ((1, "5V"), (2, "G6"), (3, "G4"), (4, "G5"), (5, "G7"), (6, "GND")):
    x, y = pad("J6", num)
    text(lab, x + 3.0, y, 0.8)
for j in ("J1", "J2", "J3", "J4"):
    x, y = pad(j, 2)
    text("OUT" + j[1], 34.6, y + 2.3, 0.8)
text("OUT pins, top to bottom:", 36.0, 50.0, 0.8)
text("GND  DATA  5V", 36.0, 51.4, 0.8, bold=True)
text("USB", 24.3, 53.2, 0.8)
text("-", pad("J5", 1)[0], 43.3, 0.9, bold=True)
text("+", pad("J5", 2)[0], 43.3, 0.9, bold=True)
text("ESP32-S3", 2.6, 31.5, 0.8, rot=90)

# ------------------------------------------------------------------ fill and save
pcbnew.ZONE_FILLER(board).Fill(board.Zones())
pcbnew.SaveBoard(OUT, board)
print("wrote", OUT)
print("J1 pads", {p.GetNumber() or "peg": tuple(round(v, 2) for v in local(p.GetPosition())) for p in fps["J1"].Pads()})
print("J5 pads", {p.GetNumber() or "peg": tuple(round(v, 2) for v in local(p.GetPosition())) for p in fps["J5"].Pads()})
